package com.infosys.service;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import com.infosys.dto.TrainDTO;
import com.infosys.entity.Train;
import com.infosys.exception.InfyRailException;
import com.infosys.repository.TrainRepository;

@Service("trainService")
@Transactional(rollbackFor = InfyRailException.class)
public class TrainServiceImpl implements TrainService {

    @Autowired
    private TrainRepository trainRepository;

    @Override
    public Integer createTrain(TrainDTO trainDTO) throws InfyRailException {
        Train train = new Train(); // id is always generated by the database
        trainDTO.copyTo(train);
        return trainRepository.save(train).getId();
    }

    @Override
    public void updateFare(Integer trainId, Double fare) throws InfyRailException {
        if (fare == null || fare <= 0) {
            throw new InfyRailException("Service.INVALID_FARE");
        }
        Train train = trainRepository.findById(trainId)
                .orElseThrow(() -> new InfyRailException("Service.TRAIN_NOT_FOUND"));
        train.setFare(fare);
    }
}
